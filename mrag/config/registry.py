def registry_path(root_dir: Path) -> Path:
    return Path(root_dir) / REGISTRY_FILENAME


def load_registry(path: Path) -> KnowledgeRegistry:
    """Read and validate a knowledge_registry.yaml file."""
    if not Path(path).exists():
        raise FileNotFoundError(f"knowledge_registry.yaml not found at {path}")
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    return KnowledgeRegistry(**data)


def _str_presenter(dumper: yaml.Dumper, value: str) -> Any:
    """Use literal block style for multi-line strings (improves readability of
    the registry's agent_instructions section)."""
    if "\n" in value:
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


class _RegistryDumper(yaml.SafeDumper):
    pass


_RegistryDumper.add_representer(str, _str_presenter)


def dump_registry(registry: KnowledgeRegistry, path: Path) -> Path:
    """Write a knowledge_registry.yaml file to disk; returns the written path."""
    data = registry.model_dump()
    Path(path).write_text(
        yaml.dump(
            data,
            Dumper=_RegistryDumper,
            default_flow_style=False,
            sort_keys=False,
            allow_unicode=True,
            width=120,
        ),
        encoding="utf-8",
    )
    return Path(path)


def registry_json_schema() -> dict[str, Any]:
    """Return the JSON Schema for the knowledge_registry.yaml file."""
    return KnowledgeRegistry.model_json_schema()


