"""KnowledgeRegistry — aggregate metadata for multiple mrag KB projects.

`knowledge_registry.yaml` lives under a root directory containing several mrag
KB project subdirectories. It is generated by `mrag registry generate` from
each subdirectory's `kb_information.yaml` and `mrag.yaml`, and is read by
external agents (Agentic RAG workflows) to discover and select KBs.

Path semantics: each `knowledge_bases[].path` is **relative to the directory
containing the registry file itself** and emitted in POSIX form (./kb-device).
This makes the registry portable across machines and directory moves.

See:
  - dev_docs/01_EXTENSION_STAGE_1/MRAG_KB_INFORMATION_INIT_SPEC.md §15
  - dev_docs/01_EXTENSION_STAGE_1/DESIGN_V18_INSPECT_REGISTRY.md §2-§3.2
"""
from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field, field_validator

from mrag.config.kb_info import KbInformationConfig


REGISTRY_FILENAME = "knowledge_registry.yaml"

_DEFAULT_SELECTION_POLICY = (
    "Select the most relevant knowledge base based on the user's question. "
    "If the question spans multiple domains, search multiple knowledge bases."
)

_DEFAULT_SEARCH_COMMAND_TEMPLATE = (
    'cd {path}\n'
    'mrag search "{query}" --profile {profile} --json\n'
)


class RegistryAgentInstructions(BaseModel):
    selection_policy: str = _DEFAULT_SELECTION_POLICY
    search_command_template: str = _DEFAULT_SEARCH_COMMAND_TEMPLATE


class RegistryKnowledgeBase(BaseModel):
    id: str
    path: str
    name: str
    description: str = ""
    tags: list[str] = Field(default_factory=list)
    best_for: list[str] = Field(default_factory=list)
    avoid_for: list[str] = Field(default_factory=list)
    preferred_profiles: list[str] = Field(default_factory=lambda: ["default"])
    example_queries: list[str] = Field(default_factory=list)

    @field_validator("id")
    @classmethod
    def _validate_id(cls, v: str) -> str:
        if not v:
            raise ValueError("knowledge_bases[].id must not be empty")
        return v

    @field_validator("path")
    @classmethod
    def _validate_path(cls, v: str) -> str:
        if not v:
            raise ValueError("knowledge_bases[].path must not be empty")
        return v

    @field_validator("name")
    @classmethod
    def _validate_name(cls, v: str) -> str:
        if not v:
            raise ValueError("knowledge_bases[].name must not be empty")
        return v


class KnowledgeRegistry(BaseModel):
    """Top-level knowledge_registry.yaml schema (version 1)."""

    version: Literal[1] = 1
    generated_at: str
    agent_instructions: RegistryAgentInstructions = Field(
        default_factory=RegistryAgentInstructions
    )
    knowledge_bases: list[RegistryKnowledgeBase] = Field(default_factory=list)


