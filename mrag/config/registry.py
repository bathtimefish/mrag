# Construction helpers
# ---------------------------------------------------------------------------


def now_utc_iso() -> str:
    """Return current UTC time as an ISO 8601 string (seconds precision)."""
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def to_relative_posix_path(kb_dir: Path, registry_dir: Path) -> str:
    """Build the POSIX relative path used in the registry's `path` field.

    Uses `os.path.relpath` so traversal upward via `..` is supported (allowing
    the registry to be written to a sibling/parent dir relative to the KB).
    The result is always prefixed with `./` for simple subdirs, or starts
    with `../` for upward traversal.
    """
    rel = os.path.relpath(
        Path(kb_dir).resolve(),
        Path(registry_dir).resolve(),
    )
    # Convert to POSIX form (Windows: \ → /)
    rel_posix = Path(rel).as_posix()
    if not rel_posix.startswith(".."):
        rel_posix = "./" + rel_posix
    return rel_posix


def from_kb_information(
    kb_info: KbInformationConfig,
    relative_path: str,
) -> RegistryKnowledgeBase:
    """Convert a project's kb_information.yaml + relative path into a registry entry."""
    return RegistryKnowledgeBase(
        id=kb_info.knowledge_base.id,
        path=relative_path,
        name=kb_info.knowledge_base.name,
        description=kb_info.knowledge_base.description,
        tags=list(kb_info.agent_usage.tags),
        best_for=list(kb_info.agent_usage.best_for),
        avoid_for=list(kb_info.agent_usage.avoid_for),
        preferred_profiles=list(kb_info.agent_usage.preferred_profiles),
        example_queries=list(kb_info.agent_usage.example_queries),
    )


